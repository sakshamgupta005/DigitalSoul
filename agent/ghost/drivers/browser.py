import asyncio
import json
import os
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit

import httpx

from ..execution.context import typed
from ..execution.errors import GhostError
from .browser_network import BrowserNetwork


def browser_executable():
    configured = os.environ.get("DIGITALSOUL_BROWSER_EXECUTABLE")
    if configured:
        if not Path(configured).is_file():
            raise GhostError("APP_UNREACHABLE", "Browser executable does not exist", 503)
        return configured
    if os.name == "nt":
        from ..browser.edge_session import browser_order
        installs = {"brave": [("PROGRAMFILES", "BraveSoftware/Brave-Browser/Application/brave.exe"),
                              ("LOCALAPPDATA", "BraveSoftware/Brave-Browser/Application/brave.exe")],
                    "chrome": [("PROGRAMFILES", "Google/Chrome/Application/chrome.exe")],
                    "edge": [("PROGRAMFILES(X86)", "Microsoft/Edge/Application/msedge.exe"),
                             ("PROGRAMFILES", "Microsoft/Edge/Application/msedge.exe")]}
        for name in browser_order():  # the user's default browser first
            for root, suffix in installs[name]:
                candidate = Path(os.environ.get(root, "")) / suffix
                if candidate.is_file():
                    return str(candidate)
    return None


# Fixed adapter code, never generated by a model. JSON.stringify avoids Actor's
# scalar string-conversion ambiguity for booleans and numbers.
ELEMENT_STATE = """() => JSON.stringify({
    tag:this.tagName, testid:this.getAttribute('data-testid'), type:this.getAttribute('type'),
    disabled:!!this.disabled, visible:!!this.getClientRects().length && getComputedStyle(this).visibility!=='hidden',
    value:this.value==null?null:this.value, text:(this.innerText||this.textContent||'').trim(),
    name:this.getAttribute('aria-label') || Array.from(this.labels||[]).map(x=>x.textContent.trim()).join(' ') || (this.innerText||'').trim()
})"""


class BrowserDriver:
    def __init__(self, policy, session=None, profile=".ghost/chrome", headless=False, monitor=None, read_json=None):
        self.policy, self.browser = policy, session
        self.profile, self.headless = profile, headless
        self.pages, self.responses = {}, {}
        self.network, self.read_json = monitor, read_json
        self._owned, self._started = session is None, False

    async def start(self):
        if self._started:
            return self
        if self.browser is None:
            os.environ.setdefault("ANONYMIZED_TELEMETRY", "false")
            from browser_use import Browser
            Path(self.profile).mkdir(parents=True, exist_ok=True)
            self.browser = Browser(
                user_data_dir=str(Path(self.profile).resolve()), headless=self.headless,
                executable_path=browser_executable(), is_local=True, use_cloud=False,
                allowed_domains=[p.origin for p in self.policy.apps.values()],
                enable_default_extensions=False, auto_download_pdfs=False,
                downloads_path=str((Path(self.profile).parent / "downloads").resolve()),
            )
        await self.browser.start()
        self.network = self.network or BrowserNetwork(self.browser, self.policy)
        await self.network.start()
        self._started = True
        return self

    async def page(self, app):
        self.policy.app(app)
        await self.start()
        if app not in self.pages:
            page = await self.browser.new_page()
            await self.network.attach(page)
            self.pages[app] = page
        return self.pages[app]

    async def state(self, element):
        return json.loads(await element.evaluate(ELEMENT_STATE))

    async def candidates(self, page, spec):
        by, value = spec["by"], spec.get("value", "")
        if by in ("testid", "css"):
            selector = f'[data-testid={json.dumps(value, ensure_ascii=False)}]' if by == "testid" else value
            return await page.get_elements_by_css_selector(selector)
        if by == "xpath":
            paths = json.loads(await page.evaluate("""(expression) => {
                const nodes=document.evaluate(expression,document,null,XPathResult.ORDERED_NODE_SNAPSHOT_TYPE,null), paths=[];
                if(nodes.snapshotLength>500) throw new Error('Too many XPath matches');
                for(let i=0;i<nodes.snapshotLength;i++) {
                    let e=nodes.snapshotItem(i),path=[];
                    if(!e||e.nodeType!==1) continue;
                    while(e) {let index=1,s=e;while((s=s.previousElementSibling)) index++;
                        path.unshift(e.tagName.toLowerCase()+':nth-child('+index+')');e=e.parentElement;}
                    paths.push(path.join(' > '));
                }return JSON.stringify(paths);
            }""", value))
            elements = []
            for path in paths:
                elements.extend(await page.get_elements_by_css_selector(path))
            return elements
        if by == "role":
            selectors = {"button": 'button,input[type="button"],input[type="submit"],[role="button"]',
                         "combobox": 'select,[role="combobox"]',
                         "textbox": 'textarea,input:not([type]),input[type="text"],[role="textbox"]'}
            if spec["role"] not in selectors:
                raise GhostError("POLICY_BLOCKED", "Role is not registered", 403)
            selector = selectors[spec["role"]]
        elif by == "label":
            selector = "input,select,textarea,button,[aria-label]"
        elif by == "text":
            selector = "body *"
        else:
            raise GhostError("POLICY_BLOCKED", "Browser locator is unsupported", 403)
        elements = await page.get_elements_by_css_selector(selector)
        if len(elements) > 500:
            raise GhostError("LOCATOR_AMBIGUOUS", "Locator search exceeds the adapter bound")
        matches = []
        for element in elements:
            state = await self.state(element)
            if state["text" if by == "text" else "name"] == (spec["name"] if by == "role" else value):
                matches.append(element)
        return matches

    async def resolve(self, page, specs):
        selected, identity = None, None
        for spec in specs:
            elements = await self.candidates(page, spec)
            if len(elements) > 1:
                raise GhostError("LOCATOR_AMBIGUOUS", "Locator matched multiple elements")
            if not elements:
                continue
            element = elements[0]
            node_id = (await element.get_basic_info())["backendNodeId"]
            if identity is not None and identity != node_id:
                raise GhostError("LOCATOR_AMBIGUOUS", "Alternative locators identify different targets")
            selected, identity = element, node_id
        if selected is None or not (await self.state(selected))["visible"]:
            raise GhostError("LOCATOR_NOT_FOUND", "Registered element is not visible")
        return selected

    async def current_url(self, app, page):
        return self.policy.url(app, await page.get_url())

    async def field_state(self, page, testid):
        elements = await self.candidates(page, {"by": "testid", "value": testid})
        if len(elements) != 1:
            raise GhostError("GUARD_TRIGGERED", "Registered evidence field is unavailable")
        return await self.state(elements[0])

    async def prepare(self, step):
        page = await self.page(step["app"])
        if getattr(self.network, "failure", None):
            raise GhostError("GUARD_TRIGGERED", "Browser network interception is unavailable")
        if step.get("verb") == "navigate":
            return {"destination": self.policy.url(step["app"], step["input"])}
        url = await self.current_url(step["app"], page)
        if step["kind"] == "assert":
            return {"url": url}
        element = await self.resolve(page, step["locators"])
        state = await self.state(element)
        registered = self.policy.app(step["app"])
        if (step["verb"], state["testid"]) not in registered.actions:
            raise GhostError("POLICY_BLOCKED", "Resolved element is not a registered capability", 403)
        if state["disabled"]:
            raise GhostError("GUARD_TRIGGERED", "Registered control is disabled")
        if step["verb"] == "click":
            label = {"save-btn": "Save", "post-team-note-btn": "Post Weekly Summary"}.get(state["testid"])
            if state["tag"] != "BUTTON" or not label or state["name"] != label:
                raise GhostError("GUARD_TRIGGERED", "Registered button identity changed")
        record = {}
        if step["app"] == "acme-crm":
            record["plan"] = (await self.field_state(page, "customer-plan"))["text"]
            try:
                record["last_login_days"] = typed(float((await self.field_state(page, "last-login-days"))["text"]), "number")
            except ValueError as exc:
                raise GhostError("GUARD_TRIGGERED", "Customer evidence changed type") from exc
            if any(record.get(k) != v for k, v in step.get("_expected_record", {}).items()):
                raise GhostError("GUARD_TRIGGERED", "Customer decision evidence changed")
        fields = {}
        for verb, testid in registered.actions:
            if verb in ("set_field", "select_option"):
                elements = await self.candidates(page, {"by": "testid", "value": testid})
                if len(elements) == 1:
                    fields[testid] = (await self.state(elements[0]))["value"]
        if any(fields.get(k) != v for k, v in step.get("_expected_fields", {}).items()):
            raise GhostError("GUARD_TRIGGERED", "Draft changed since the reviewed fill step")
        identity = {k: state[k] for k in ("testid", "tag", "type", "disabled", "name")}
        identity["backend_node_id"] = (await element.get_basic_info())["backendNodeId"]
        return {"url": url, "target": identity, "fields": fields, "record": record}

    async def check(self, app, condition, locators):
        page = await self.page(app)
        url = await self.current_url(app, page)
        kind, value = condition["type"], condition.get("value")
        if kind == "url_matches":
            return urlsplit(url).path == value
        if kind == "record_id_matches":
            return (await self.field_state(page, "customer-record-id"))["text"] == value
        if kind == "network_2xx":
            return bool(self.responses.get((app, value)))
        elements = await self.candidates(page, locators[condition["locator_ref"]])
        if len(elements) != 1:
            return False
        state = await self.state(elements[0])
        if kind == "element_visible":
            return state["visible"]
        if kind == "field_equals":
            return state["value"] == str(value)
        raise GhostError("VALIDATION_ERROR", "Unsupported condition", 422)

    async def perform(self, step, target):
        page = await self.page(step["app"])
        verb = step.get("verb")
        if verb == "navigate":
            await page.goto(self.policy.url(step["app"], step["input"]))
            await self.wait_ready(page)
            await self.current_url(step["app"], page)
            return
        if verb == "assert_state":
            return
        element = await self.resolve(page, step["locators"])
        if verb == "read_field":
            if step["output_type"] == "string[]":
                try:
                    return typed(json.loads(await element.get_attribute("data-account-ids") or "null"), "string[]")
                except (ValueError, TypeError) as exc:
                    raise GhostError("VALIDATION_ERROR", "Adapter requires data-account-ids JSON", 422) from exc
            state = await self.state(element)
            raw = state["value"] if state["value"] is not None else state["text"]
            if step["output_type"] == "number":
                try:
                    return typed(float(raw.strip()), "number")
                except ValueError as exc:
                    raise GhostError("VALIDATION_ERROR", "Field is not a number", 422) from exc
            if step["output_type"] == "boolean":
                if raw not in ("true", "false"):
                    raise GhostError("VALIDATION_ERROR", "Boolean field must be true or false", 422)
                return raw == "true"
            return raw.strip()
        if verb == "wait_visible":
            return
        if verb == "select_option":
            await element.select_option(str(step["input"]))
            return
        if verb == "set_field":
            await element.fill(str(step["input"]))
            return
        if verb == "click":
            paths = [c["value"] for c in step["post"] if c["type"] == "network_2xx"]
            if len(paths) != 1:
                raise GhostError("POLICY_BLOCKED", "Click requires one mutation response contract", 403)
            path = paths[0]
            self.responses[(step["app"], path)] = False
            url = self.policy.url(step["app"], self.policy.app(step["app"]).origin + path)
            self.responses[(step["app"], path)] = await self.network.mutation(page, url, element.click)
            return
        raise GhostError("POLICY_BLOCKED", "Unsupported browser action", 403)

    async def wait_ready(self, page):
        async with asyncio.timeout(10):
            while (await page.evaluate("() => document.readyState")) not in ("interactive", "complete"):
                await asyncio.sleep(0.05)

    async def get_json(self, app, path):
        url = self.policy.url(app, self.policy.app(app).origin + path)
        if self.read_json:
            return await self.read_json(url)
        page = await self.page(app)
        cookies = await self.network.cookies(page, url)
        async with httpx.AsyncClient(timeout=10, trust_env=False, follow_redirects=False, cookies=cookies) as client:
            response = await client.get(url)
            if response.status_code != 200:
                raise GhostError("POSTCONDITION_FAILED", "Independent outcome read failed")
            return response.json()

    async def outcome(self, check):
        app, args = check["app"], check["args"]
        if check["type"] != "app_api":
            raise GhostError("POLICY_BLOCKED", "Outcome adapter is not registered", 403)
        if app == "acme-crm" and check["check"] == "tag_equals_for_all":
            expected = args["expected_by_id"]
            if set(args["ids"]) != set(expected):
                return False
            for account in args["ids"]:
                if (await self.get_json(app, "/api/customers/" + quote(account, safe=""))).get("tag") != expected[account]:
                    return False
            return True
        if app == "acme-portal" and check["check"] == "team_note_exists":
            notes = await self.get_json(app, "/api/team/notes")
            return sum(n.get("body") == args["containing"] for n in notes) == args["expected_count"]
        raise GhostError("POLICY_BLOCKED", "Outcome adapter is not registered", 403)

    async def reconcile(self, intent):
        step, target = intent["step"], intent["target"]
        app = step["app"]
        self.policy.classify(step)
        if step["step_id"] == "s5_save_cust" and app == "acme-crm":
            account = unquote(urlsplit(target["url"]).path.rsplit("/", 1)[1])
            return (await self.get_json(app, "/api/customers/" + quote(account, safe=""))).get("tag") == target["fields"].get("tag-select")
        if step["step_id"] == "s6_post_summary" and app == "acme-portal":
            notes = await self.get_json(app, "/api/team/notes")
            return sum(n.get("body") == target["fields"].get("team-note-body") for n in notes) == 1
        return False

    async def restore_navigation(self, navigation):
        for app, url in navigation.items():
            page = await self.page(app)
            await page.goto(self.policy.url(app, url))
            await self.wait_ready(page)
            await self.current_url(app, page)

    async def close(self):
        if self.network:
            await self.network.close()
        if self._owned and self.browser and self._started:
            await self.browser.kill()
        self._started = False
