from typing import Protocol


class Driver(Protocol):
    async def prepare(self, step: dict) -> dict:
        """Return a fresh stable target/effect snapshot; never mutate the app."""
        ...

    async def check(self, app: str, condition: dict, locators: list) -> bool: ...
    async def perform(self, step: dict, target: dict): ...
    async def outcome(self, check: dict) -> bool: ...
    async def reconcile(self, intent: dict) -> bool: ...
    async def close(self): ...
